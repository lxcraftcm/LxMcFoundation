package com.lx.mc.foundation.persistence;

/**
 * 定义可持久化数据快照必须提供的唯一标识和修订号。
 *
 * <p>作者：lxcraftcm</p>
 * <p>创建时间：2026-07-31 13:04</p>
 *
 * <p>主要逻辑：</p>
 * <ol>
 *     <li>使用唯一标识确定数据文件或数据库记录。</li>
 *     <li>使用递增修订号保证异步写入顺序。</li>
 * </ol>
 *
 * <p>主要调用方：领域 DTO、异步持久化队列和持久化适配器。</p>
 * <p>约束：实现类必须是不会在入队后继续变化的不可变快照。</p>
 */
public interface PersistedRecord {

    /**
     * 获取持久化记录的稳定唯一标识。
     *
     * <p>作者：lxcraftcm</p>
     * <p>创建时间：2026-07-31 13:04</p>
     * <p>主要逻辑：返回用于定位持久化记录的唯一键。</p>
     * <p>主要调用方：JSON 文件适配器和异步持久化队列。</p>
     *
     * @return 非空且稳定的记录唯一标识
     */
    String getId();

    /**
     * 获取持久化记录的单调递增修订号。
     *
     * <p>作者：lxcraftcm</p>
     * <p>创建时间：2026-07-31 13:04</p>
     * <p>主要逻辑：返回当前快照对应的数据修改顺序。</p>
     * <p>主要调用方：异步持久化队列的过期任务判断逻辑。</p>
     *
     * @return 大于或等于零的记录修订号
     */
    long getRevision();
}
